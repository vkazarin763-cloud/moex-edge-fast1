"""Moving-block bootstrap inference for chronological strategy returns.

The test targets the unconditional mean net return per observation against
zero. It preserves short-range serial dependence by resampling contiguous
circular blocks. It is not a universal test for strategy profitability:
overlapping positions, heteroskedasticity, regime changes, and selection
effects still require a carefully designed research protocol.
"""
from __future__ import annotations

import math
import random
from collections.abc import Sequence
from statistics import mean
from typing import Any


class BootstrapInputError(ValueError):
    """Invalid chronological return series or bootstrap configuration."""


def moving_block_bootstrap_mean_test(
    returns: Sequence[float],
    *,
    block_length: int,
    resamples: int = 5000,
    alpha: float = 0.05,
    seed: int = 1729,
) -> dict[str, Any]:
    """Test H0: mean net return is zero using a circular moving-block bootstrap.

    Returns must be chronological, one value per non-overlapping evaluation
    observation/trade. The null distribution is generated by centering the
    observed series and resampling contiguous blocks. The reported two-sided
    p-value uses the finite-resample plus-one correction. A percentile
    confidence interval is also returned for the uncentered mean.
    """
    if isinstance(returns, (str, bytes)) or not isinstance(returns, Sequence):
        raise BootstrapInputError("returns must be a chronological numeric sequence")
    values = []
    for index, raw in enumerate(returns):
        if isinstance(raw, bool) or not isinstance(raw, (int, float)):
            raise BootstrapInputError(f"return at index {index} must be numeric")
        value = float(raw)
        if not math.isfinite(value):
            raise BootstrapInputError(f"return at index {index} must be finite")
        values.append(value)
    n = len(values)
    if n < 20:
        raise BootstrapInputError("at least 20 chronological observations are required")
    if isinstance(block_length, bool) or not isinstance(block_length, int) or not 1 <= block_length <= n // 2:
        raise BootstrapInputError("block_length must be an integer from 1 to floor(n/2)")
    if isinstance(resamples, bool) or not isinstance(resamples, int) or resamples < 999:
        raise BootstrapInputError("resamples must be an integer >= 999")
    if isinstance(alpha, bool) or not isinstance(alpha, (int, float)):
        raise BootstrapInputError("alpha must be numeric")
    alpha = float(alpha)
    if not math.isfinite(alpha) or not 0.0 < alpha < 1.0:
        raise BootstrapInputError("alpha must be finite and between 0 and 1")
    if isinstance(seed, bool) or not isinstance(seed, int):
        raise BootstrapInputError("seed must be an integer")

    observed = mean(values)
    centered = [value - observed for value in values]
    rng = random.Random(seed)
    null_means = []
    alternative_means = []
    blocks_needed = (n + block_length - 1) // block_length

    for _ in range(resamples):
        null_sample = []
        alt_sample = []
        for _block in range(blocks_needed):
            start = rng.randrange(n)
            take = min(block_length, n - len(null_sample))
            for offset in range(take):
                index = (start + offset) % n
                null_sample.append(centered[index])
                alt_sample.append(values[index])
        null_means.append(mean(null_sample))
        alternative_means.append(mean(alt_sample))

    extreme = sum(abs(value) >= abs(observed) for value in null_means)
    p_value = (extreme + 1) / (resamples + 1)
    alternative_means.sort()

    def quantile(sorted_values: list[float], probability: float) -> float:
        position = (len(sorted_values) - 1) * probability
        lower = int(math.floor(position))
        upper = int(math.ceil(position))
        if lower == upper:
            return sorted_values[lower]
        weight = position - lower
        return sorted_values[lower] * (1.0 - weight) + sorted_values[upper] * weight

    lower_ci = quantile(alternative_means, alpha / 2.0)
    upper_ci = quantile(alternative_means, 1.0 - alpha / 2.0)
    return {
        "status": "TESTED",
        "test": "circular_moving_block_bootstrap_mean",
        "null_hypothesis": "population_mean_net_return_equals_zero",
        "alternative_hypothesis": "population_mean_net_return_differs_from_zero",
        "observations": n,
        "block_length": block_length,
        "resamples": resamples,
        "seed": seed,
        "alpha": alpha,
        "observed_mean": observed,
        "two_sided_p_value": p_value,
        "confidence_interval": {
            "method": "percentile_moving_block_bootstrap",
            "lower": lower_ci,
            "upper": upper_ci,
            "level": 1.0 - alpha,
        },
        "reject_null": p_value <= alpha,
        "safety": {
            "chronological_order_assumed": True,
            "serial_dependence_preserved_within_blocks": True,
            "circular_block_boundary_wraparound": True,
            "p_value_is_approximate": True,
            "block_length_requires_sensitivity_analysis": True,
            "overlapping_trade_dependence_fully_resolved": False,
            "multiple_testing_correction_still_required": True,
            "independent_holdout_still_required": True,
            "strategy_approval": "NOT_APPROVED",
        },
    }
